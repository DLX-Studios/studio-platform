/// Collect `item.<field>` reads from one expression.
fn collect_expression_reads(
    expression: &StudioExpression,
    item: &str,
    fields: &mut Vec<(String, ContentTy)>,
    component: &ComponentDefinition,
) -> Result<(), StudioEmitError> {
    match expression {
        StudioExpression::ReadLocal(path) => {
            if path == item {
                return Ok(());
            }
            if let Some(field) = path
                .strip_prefix(item)
                .and_then(|rest| rest.strip_prefix('.'))
            {
                if field.is_empty() || field.contains('.') {
                    return Err(emit_failed("nested item reads"));
                }
                let ty = match content_ty(component, None, expression) {
                    ContentTy::String | ContentTy::Number | ContentTy::Boolean => {
                        content_ty(component, None, expression)
                    }
                    ContentTy::Other => return Err(emit_failed("untyped item reads")),
                };
                if let Some(existing) = fields.iter().find(|(name, _)| name == field) {
                    if existing.1 != ty {
                        return Err(emit_failed("item fields changing type"));
                    }
                } else {
                    fields.push((field.to_owned(), ty));
                }
                return Ok(());
            }
            return Err(emit_failed("unbound locals in rows"));
        }
        StudioExpression::Literal(_)
        | StudioExpression::ReadState(_)
        | StudioExpression::ReadDerived(_)
        | StudioExpression::ReadProp(_) => Ok(()),
        StudioExpression::Unary { operand, .. } => {
            collect_expression_reads(operand, item, fields, component)
        }
        StudioExpression::Binary { left, right, .. } => {
            collect_expression_reads(left, item, fields, component)?;
            collect_expression_reads(right, item, fields, component)
        }
        StudioExpression::Conditional {
            condition,
            consequent,
            alternate,
        } => {
            collect_expression_reads(condition, item, fields, component)?;
            collect_expression_reads(consequent, item, fields, component)?;
            collect_expression_reads(alternate, item, fields, component)
        }
        StudioExpression::Array(elements) => elements
            .iter()
            .try_for_each(|element| collect_expression_reads(element, item, fields, component)),
        StudioExpression::Record(entries) => entries
            .iter()
            .try_for_each(|(_, value)| collect_expression_reads(value, item, fields, component)),
        StudioExpression::CallApprovedFunction { arguments, .. } => arguments
            .iter()
            .try_for_each(|argument| collect_expression_reads(argument, item, fields, component)),
    }
}
